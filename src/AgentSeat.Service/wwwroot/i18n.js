export function resolveLanguage(preferences = []) {
  for (const value of Array.isArray(preferences) ? preferences : [preferences]) {
    if (typeof value !== 'string') continue;
    const language = value.trim().toLowerCase().split(/[-_]/)[0];
    if (Object.hasOwn(languageNames, language)) return language;
  }
  return 'en';
}

export function translate(language, key, values = {}) {
  const template = messages[resolveLanguage(language)]?.[key] ?? messages.en[key] ?? key;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (placeholder, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}

export function errorKey(error) {
  const key = `error.${error?.code}`;
  if (Object.hasOwn(messages.en, key)) return key;
  if (error?.name === 'TimeoutError' || error?.name === 'AbortError') return 'error.timeout';
  if (error instanceof TypeError) return 'error.network';
  return 'error.unknown';
}

export function seatStateKey(status) {
  if (status.refused || status.agentControlEnabled === false) return 'seats.refused';
  if (status.paused) return 'seats.paused';
  if (status.stopped) return 'seats.stopped';
  if (!status.sessionAvailable) return 'seats.offline';
  if (status.busy) return 'seats.busy';
  if (status.helperRunning === false) return 'seats.helperPending';
  return 'seats.ready';
}

export function localizeCheck(language, check, views = []) {
  const account = check.code.startsWith('account_');
  const id = account ? check.code.slice(8) : '';
  const code = account ? 'account' : check.code;
  const values = { name: views.find(view => view.seat.id === id)?.seat.displayName ?? id,
    port: check.title.match(/\d+/)?.[0] ?? '?' };
  const titleKey = `checks.${code}.title`, detailKey = `checks.${code}.${check.status}`;
  return {
    title: Object.hasOwn(messages.en, titleKey) ? translate(language, titleKey, values) : check.title,
    detail: Object.hasOwn(messages.en, detailKey) ? translate(language, detailKey, values) : check.detail,
  };
}
